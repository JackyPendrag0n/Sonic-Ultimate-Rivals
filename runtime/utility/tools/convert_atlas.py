#!/usr/bin/env python3
"""Converts PPSSPP's assets/ppge_atlas.zim + ppge_atlas.meta (zstd-compressed) into C++ byte arrays the
utility library embeds: the ZIM image recompressed with zlib (ZIM_ZLIB_COMPRESSED instead of
ZIM_ZSTD_COMPRESSED) and the atlas metadata rewritten as version 0 (uncompressed arrays) and then
zlib-compressed as a whole (the library inflates it), so the library needs zlib but not zstd. Uses the system libzstd.so.1 through ctypes, once, at generation time.

  convert_atlas.py <ppsspp>/assets out_dir

Part of the rcsm utility extraction (GPL-2.0+; the atlas is PPSSPP's, same license).
"""
import ctypes
import ctypes.util
import os
import struct
import sys
import zlib

zstd = ctypes.CDLL(ctypes.util.find_library("zstd") or "libzstd.so.1")
zstd.ZSTD_getFrameContentSize.restype = ctypes.c_ulonglong
zstd.ZSTD_getFrameContentSize.argtypes = [ctypes.c_char_p, ctypes.c_size_t]
zstd.ZSTD_decompress.restype = ctypes.c_size_t
zstd.ZSTD_decompress.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_size_t]


def unzstd(data, size=None):
    if size is None:
        size = zstd.ZSTD_getFrameContentSize(data, len(data))
    out = ctypes.create_string_buffer(size)
    n = zstd.ZSTD_decompress(out, size, data, len(data))
    if n != size:
        raise RuntimeError("zstd decompression failed (%d of %d)" % (n, size))
    return out.raw[:n]


def convert_zim(zim):
    magic, w, h, flags = struct.unpack("<4sIII", zim[:16])
    assert magic == b"ZIMG" and flags & 0x1000, "expected a zstd ZIM"
    bpp = {0: 4, 1: 2, 2: 2}[flags & 15]
    assert not flags & 16, "mips not supported"
    raw = unzstd(zim[16:], w * h * bpp)
    flags = (flags & ~0x1000) | 0x100
    return struct.pack("<4sIII", magic, w, h, flags) + zlib.compress(raw, 9)


def convert_meta(meta):
    magic, version, nfonts, nimages = struct.unpack("<iiii", meta[:16])
    out = bytearray(struct.pack("<iiii", magic, 0, nfonts, nimages))
    pos = 16

    def array():
        nonlocal pos
        if version >= 1:
            (size,) = struct.unpack("<I", meta[pos:pos + 4])
            data = unzstd(meta[pos + 4:pos + 4 + size])
            pos += 4 + size
            return data
        raise RuntimeError("version 0 meta needs struct sizes; already uncompressed?")

    out += array()  # images
    for _ in range(nfonts):
        out += meta[pos:pos + 56]  # AtlasFontHeader
        pos += 56
        out += array()  # ranges
        out += array()  # chars
    assert pos == len(meta), "trailing data in meta"
    return bytes(out)


def c_array(name, data):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 32):
        lines.append("\t" + ",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    src, out = sys.argv[1], sys.argv[2]
    zim = convert_zim(open(os.path.join(src, "ppge_atlas.zim"), "rb").read())
    meta = convert_meta(open(os.path.join(src, "ppge_atlas.meta"), "rb").read())
    with open(os.path.join(out, "ppge_atlas.inc"), "w") as f:
        f.write("// Generated by runtime/utility/tools/convert_atlas.py from PPSSPP's assets/ppge_atlas.zim and\n")
        f.write("// ppge_atlas.meta (zstd -> zlib / uncompressed). GPL-2.0+ (PPSSPP).\n")
        f.write(c_array("g_ppgeAtlasZim", zim))
        f.write("static const unsigned g_ppgeAtlasMetaSize = %d;\n" % len(meta))
        f.write(c_array("g_ppgeAtlasMetaZ", zlib.compress(meta, 9)))
    print("zim %d bytes, meta %d bytes" % (len(zim), len(meta)))


if __name__ == "__main__":
    main()
