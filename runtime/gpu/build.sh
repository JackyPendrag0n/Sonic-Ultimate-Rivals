#!/bin/bash
# Builds PPSSPP's GE list processor with its software renderer and its OpenGL hardware renderer
# (GPU_GLES on thin3d/GLRenderManager, run single-threaded) plus the sceGe HLE layer and the rcsm
# presenter (GPL-2.0+, see LICENSE.TXT) into build/libpspgpu.a, and the tests build/test_ge (software,
# no window) and build/test_ge_gl (either backend in an SDL OpenGL window; tools/compare_backends.sh).
#
#   runtime/gpu/build.sh          build libpspgpu.a and the tests
#   runtime/gpu/build.sh lib      library only
#   runtime/gpu/build.sh clean
#
# Link the library into the runtime with: build/libpspgpu.a -lpthread. No -lGL: the OpenGL functions
# are loaded through ge_gl_init()'s get_proc (shim/GL/glew.h, generated by tools/gen_gl_loader.py).
# API: ge_soft.h.
set -e
GPU="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$GPU/../.." && pwd)"
OUT="$ROOT/build"
OBJ="$OUT/gpu_obj"
CXX="${CXX:-g++}"
CC="${CC:-gcc}"
JOBS="$(nproc)"

if [ "$1" = clean ]; then rm -rf "$OBJ" "$OUT/libpspgpu.a" "$OUT/test_ge" "$OUT/test_ge_gl"; exit 0; fi

# Shims first so they override PPSSPP headers; PPSSPP also uses bare "CommonTypes.h"-style includes.
INCLUDES="-I$GPU/shim -I$GPU/ppsspp -iquote $GPU/ppsspp/Common"
DEFINES="-DMASKED_PSP_MEMORY -DNDEBUG -DRCSM_GL_SINGLE_THREAD"
CXXFLAGS="${CXXFLAGS:--O2} -std=c++17 -g0 -fPIC -msse2 -fno-strict-aliasing -Wno-unused-result -Wno-deprecated-declarations -Wno-class-memaccess -Wno-format-truncation"

