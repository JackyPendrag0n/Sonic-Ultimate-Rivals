mkdir -p "$OBJ"

# Compile one source if it (or a header it depends on) is newer than its object.
compile() {
	local src="$1" o="$OBJ/$(echo "$1" | sed 's|/|_|g; s|\.cpp$|.o|; s|\.c$|.o|')"
	local d="${o%.o}.d"
	if [ -f "$o" ] && [ -f "$d" ]; then
		local deps; deps=$(sed -e 's/^[^:]*://' -e 's/\\$//' "$d")
		local stale=0
		for f in $deps; do [ "$f" -nt "$o" ] && { stale=1; break; }; done
		[ $stale = 0 ] && return 0
	fi
	echo "  CC  $src"
	case "$src" in
	*.c) $CC -O2 -fPIC $DEFINES $INCLUDES -MMD -MF "$d" -c "$GPU/$src" -o "$o" ;;
	*) $CXX $CXXFLAGS $DEFINES $INCLUDES -MMD -MF "$d" -c "$GPU/$src" -o "$o" ;;
	esac
}
export -f compile
export OBJ GPU CC CXX CXXFLAGS DEFINES INCLUDES

echo "$SOURCES" | grep -v '^$' | xargs -P "$JOBS" -I{} bash -c 'compile {}'

OBJS=$(echo "$SOURCES" | grep -v '^$' | sed 's|/|_|g; s|\.cpp$|.o|; s|\.c$|.o|' | sed "s|^|$OBJ/|")
rm -f "$OUT/libpspgpu.a"
ar rcs "$OUT/libpspgpu.a" $OBJS
echo "built $OUT/libpspgpu.a"

[ "$1" = lib ] && exit 0

compile test_ge.cpp
$CXX -o "$OUT/test_ge" "$OBJ/test_ge.o" "$OUT/libpspgpu.a" -lpng -lz -lpthread
echo "built $OUT/test_ge"
# Backend test in an SDL OpenGL window (run under xvfb-run when headless).
compile test_ge_gl.cpp
$CXX -o "$OUT/test_ge_gl" "$OBJ/test_ge_gl.o" "$OUT/libpspgpu.a" $(sdl2-config --libs) -lpng -lz -lpthread
echo "built $OUT/test_ge_gl"
