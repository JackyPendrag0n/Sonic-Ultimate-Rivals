#!/usr/bin/env python3
# Generates runtime/gpu/shim/GL/glew.h: an OpenGL function loader standing in for GLEW, for PPSSPP's
# OpenGL backend. Every gl* function the sources call becomes a pointer (rcsm_glFoo, typed from the
# system's <GL/gl.h>/<GL/glext.h> prototypes) filled by ge_gl_init()'s get_proc, so the library needs
# no -lGL and works with whatever context the frontend created.
#   python3 runtime/gpu/tools/gen_gl_loader.py
import os, re
GPU = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
decl = set()
for h in ('/usr/include/GL/gl.h', '/usr/include/GL/glext.h'):
    decl |= set(re.findall(r'^GLAPI\s[^;]*?\b(gl[A-Z]\w*)\s*\(', open(h).read(), re.M))
used = set()
scan = [os.path.join(GPU, d) for d in ('ppsspp/Common/GPU', 'ppsspp/GPU/GLES', 'ppsspp/GPU/Common', 'ppsspp/GPU')]
files = []
for d in scan:
    for root, _, names in os.walk(d):
        files += [os.path.join(root, n) for n in names if n.endswith(('.cpp', '.h'))]
files += [os.path.join(GPU, f) for f in os.listdir(GPU) if f.endswith('.cpp')]
for f in files:
    used |= set(re.findall(r'\b(gl[A-Z]\w*)\b', open(f, errors='replace').read()))
fns = sorted(used & decl)
o = ['// Generated by runtime/gpu/tools/gen_gl_loader.py - do not edit. Stands in for GLEW (rcsm GPU',
     '// extraction): each GL function PPSSPP calls is a pointer loaded by ge_gl_init(). GPL-2.0+.',
     '#pragma once',
     '#ifndef GL_GLEXT_PROTOTYPES',
     '#define GL_GLEXT_PROTOTYPES 1  // only for decltype() below: nothing links to these prototypes',
     '#endif',
     '#include <GL/gl.h>',
     '#include <GL/glext.h>',
     '#ifdef RCSM_GL_LOADER_IMPL',
     '#define RCSM_GL_FN(f) decltype(&::f) rcsm_##f;',
     '#else',
     '#define RCSM_GL_FN(f) extern decltype(&::f) rcsm_##f;',
     '#endif']
o += ['RCSM_GL_FN(%s)' % f for f in fns]
o += ['#undef RCSM_GL_FN', '#ifndef RCSM_GL_LOADER_IMPL']
o += ['#define %s rcsm_%s' % (f, f) for f in fns]
o += ['#endif',
      '// GLEW names for core enums that PPSSPP uses.',
      '#ifndef GL_MAX_CLIP_DISTANCES_EXT', '#define GL_MAX_CLIP_DISTANCES_EXT GL_MAX_CLIP_DISTANCES', '#endif',
      '#ifndef GL_MAX_CULL_DISTANCES_EXT', '#define GL_MAX_CULL_DISTANCES_EXT GL_MAX_CULL_DISTANCES', '#endif',
      '#define RCSM_GL_FUNCTIONS(X) \\']
o += ['\tX(%s) \\' % f for f in fns]
o += ['']
open(os.path.join(GPU, 'shim/GL/glew.h'), 'w').write('\n'.join(o) + '\n')
print('%d GL functions' % len(fns))
