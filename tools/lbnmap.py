"""Write the sector map of a PSP ISO as C: lbnmap.py <iso> > runtime/lbnmap.inc

Games that read the disc by sector (disc0:/sce_lbn...) compute sector numbers from the original
disc layout, so the runtime needs each file's real start sector to serve them from an extracted folder.
"""
import struct, sys
f = open(sys.argv[1], 'rb')
def rd(lba, n): f.seek(lba * 2048); return f.read(n)
out = []
def walk(lba, size, path):
    data = rd(lba, size); o = 0
    while o < len(data):
        l = data[o]
        if l == 0: o = (o // 2048 + 1) * 2048; continue
        r = data[o:o + l]; o += l
        el, sz, fl, nl = struct.unpack_from('<I', r, 2)[0], struct.unpack_from('<I', r, 10)[0], r[25], r[32]
        nm = r[33:33 + nl]
        if nm in (b'\0', b'\1'): continue
        p = path + '/' + nm.decode('latin1').split(';')[0] if path else nm.decode('latin1').split(';')[0]
        if fl & 2: walk(el, sz, p)
        else: out.append((el, sz, p))
root = rd(16, 2048)[156:190]
walk(struct.unpack_from('<I', root, 2)[0], struct.unpack_from('<I', root, 10)[0], '')
print('// generated by tools/lbnmap.py from the disc image: start sector, size, path')
for el, sz, p in sorted(out):
    print('{0x%06x, 0x%08x, "%s"},' % (el, sz, p))
