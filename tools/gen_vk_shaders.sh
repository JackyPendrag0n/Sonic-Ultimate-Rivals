#!/bin/bash
# Compiles the Vulkan renderer's shaders (runtime/ngpu/vk/*.vert, *.frag) to SPIR-V, into runtime/ngpu/ng_vk_spv.h,
# so that the build itself needs no shader compiler. Run after changing a shader; needs glslangValidator
# (Debian/Ubuntu: glslang-tools).
set -e
cd "$(dirname "$0")/../runtime/ngpu/vk"
out=../ng_vk_spv.h
tmp=$(mktemp -d)
{
  echo "// Generated by tools/gen_vk_shaders.sh from runtime/ngpu/vk: don't edit."
  echo "#pragma once"
  echo "#include <stdint.h>"
  for f in ng.vert ng.frag blit.vert blit.frag; do
    name=spv_$(echo $f | tr . _)
    glslangValidator -V --target-env vulkan1.0 --vn $name -o $tmp/$name.h $f > /dev/null
    grep -v -e '^\s*//' -e '^\s*#pragma' $tmp/$name.h | sed -e 's/^const uint32_t/static const uint32_t/'
  done
} > $out
rm -rf $tmp
echo "wrote runtime/ngpu/ng_vk_spv.h"
